-- Customer Churn Analysis - Business Insights

-- 1. The company has a churn rate of approximately 26.6%, 
--    with 1,869 customers leaving out of 7,032 total customers.

-- 2. Customers on Month-to-Month contracts exhibit significantly higher churn
--    compared to customers on One-Year and Two-Year contracts.

-- 3. Churned customers pay higher monthly charges on average (74.44)
--    than retained customers (61.30), 
--    suggesting pricing may influence customer retention.

-- 4. Customers who churn have a much lower average tenure (17.98 months) 
--    compared to retained customers (37.65 months), 
--    indicating newer customers are more likely to leave.

-- 5. Fiber Optic internet users represent a high-risk customer segment, 
--    showing the highest churn levels among all internet service types.

-- 6. Customers using Electronic Check as their payment method
--    exhibit the highest churn levels, 
--    while automatic payment methods are associated with better retention.

-- 7. Senior Citizens demonstrate a higher tendency 
--    to churn compared to non-senior customers, 
--    making them an important target group for retention initiatives.
