/* =====================================================
Customer Churn Analysis - Business Recommendations
===================================================== */

-- 1. Encourage customers to switch from Month-to-Month
--    contracts to One-Year or Two-Year plans through
--    discounts and loyalty incentives, as long-term
--    contracts are associated with significantly lower churn.

-- 2. Implement targeted retention programs for new customers,
--    especially during their first 18 months, since customers
--    with shorter tenure are more likely to churn.

-- 3. Review Fiber Optic service quality, pricing, and customer
--    support processes, as Fiber Optic users represent the
--    highest-risk customer segment.

-- 4. Introduce personalized offers or discounts for customers
--    with high monthly charges to reduce price-related churn.

-- 5. Encourage customers to adopt automatic payment methods
--    such as Credit Card or Bank Transfer by offering small
--    incentives, as these methods are associated with lower churn.

-- 6. Develop dedicated retention campaigns for Senior Citizens,
--    including simplified support channels and personalized
--    assistance to improve customer satisfaction.

-- 7. Create an early-warning churn monitoring system to identify
--    high-risk customers based on factors such as contract type,
--    tenure, monthly charges, internet service, and payment method.




